#define MAX_IO_CARD_PORT            16         // IN, OUT 카드의 포트 최대 수
#define MAX_IO_CARD_SLOT            16         // 서브랙당 최대 IO 카드 수
#define MAX_IO_CHASSIS              10         // 최대 서브랙 수 
//#define MAX_IO_MODULE_PORT          4          // 신호기, 선로전환기 모듈 포트 최대 수
#define MAX_SIG_MODULE_PORT         4          // 신  호  기 모듈 포트 최대 수
#define MAX_SWH_MODULE_PORT         2          // 선로전환기 모듈 포트 최대 수

// MAX_IO_CARD_PORT * MAX_IO_CARD_SLOT * MAX_IO_CHASSIS
//     16 port      x      16 slot     x   10 chassis  = 2560
#define MAX_CARD_PORT               2560       // 최대 Card Port 수

// MAX_IO_CARD_SLOT * MAX_IO_CHASSIS
//     16 slot      x   10 chassis  = 160
#define MAX_IO_CARD                 160        // 최대 Card(Slot) 수

#define MAX_SIGNAL_CARD             160        // 신  호  기 모듈의 최대 수
#define MAX_SWITCH_CARD             160        // 선로전환기 모듈의 최대 수

